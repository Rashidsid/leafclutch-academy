/* ------------------------------------------------------------------ */
/* Files 6–11 carry long free text (descriptions, curricula, FAQs).    */
/* Each record's content is shipped as one base64-encoded JSON value   */
/* and decoded by the database, so the SQL text itself contains no     */
/* prose, quotes, colons or line breaks for an editor to misread.      */
/* ------------------------------------------------------------------ */

/** `jsonb_populate_record(...) r` over a base64 JSON payload shaped like the table's row. */
function record(table: string, row: Record<string, unknown>) {
  const b64 = Buffer.from(JSON.stringify(row), "utf8").toString("base64");
  return `jsonb_populate_record(null::public.${table}, convert_from(decode('${b64}', 'base64'), 'UTF8')::jsonb) r`;
}

// 6 — courses
const COURSE_COLUMNS = [
  "slug", "title", "subtitle", "description", "fee", "duration", "level", "modes",
  "badge", "is_ai_integrated", "is_featured", "is_published", "sort_order", "icon", "accent",
  "tools", "outcomes", "prerequisites", "includes", "careers", "curriculum", "faqs", "installments",
];
write(
  "6seed-courses.sql",
  "the 12 programs with curriculum, tools, FAQs and payment plan",
  seedCourses
    .map((c, i) => {
      const row = {
        slug: c.slug,
        title: c.title,
        subtitle: c.subtitle,
        description: c.description,
        fee: c.fee,
        duration: DEFAULT_DURATION,
        level: c.level,
        modes: ALL_MODES,
        badge: c.badge,
        is_ai_integrated: c.is_ai_integrated,
        is_featured: c.is_featured,
        is_published: true,
        sort_order: i + 1,
        icon: c.icon,
        accent: c.accent,
        tools: c.tools,
        outcomes: c.outcomes,
        prerequisites: c.prerequisites,
        includes: DEFAULT_INCLUDES,
        careers: c.careers,
        curriculum: curriculumFor(c.slug, c.curriculum),
        faqs: c.faqs,
        installments: DEFAULT_INSTALLMENTS,
      };
      return `-- ${i + 1}. ${c.title} — NPR ${c.fee.toLocaleString("en-IN")}
insert into public.courses (category_id, ${COURSE_COLUMNS.join(", ")})
select (select id from public.categories where slug = ${str(c.category)}), ${COURSE_COLUMNS.map((k) => `r.${k}`).join(", ")}
from ${record("courses", row)}
on conflict (slug) do nothing;`;
    })
    .join("\n\n"),
);

// 7 — mentors + course links
write(
  "7seed-mentors.sql",
  "mentors and the courses they teach",
  seedMentors
    .map(
      (m, i) => `-- ${m.name}
insert into public.mentors (slug, name, role, bio, photo_url, expertise, linkedin_url, sort_order)
select r.slug, r.name, r.role, r.bio, r.photo_url, r.expertise, r.linkedin_url, r.sort_order
from ${record("mentors", { slug: m.slug, name: m.name, role: m.role, bio: m.bio, photo_url: m.photo_url, expertise: m.expertise, linkedin_url: m.linkedin_url, sort_order: i + 1 })}
on conflict (slug) do nothing;

insert into public.course_mentors (course_id, mentor_id)
select c.id, m.id
from public.courses c
cross join public.mentors m
where m.slug = ${str(m.slug)}
  and c.slug in (${m.courses.map(str).join(", ")})
on conflict do nothing;`,
    )
    .join("\n\n"),
);

