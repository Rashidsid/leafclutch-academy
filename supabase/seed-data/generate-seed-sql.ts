import { curriculumOutlines } from "./curriculum-outlines.ts";
import { parseOutline } from "../../src/lib/curriculum.ts";

/** Detailed Lesson → Section → Points curriculum when an outline exists, else the short one. */
const curriculumFor = (slug: string, fallback: unknown) =>
  curriculumOutlines[slug] ? parseOutline(curriculumOutlines[slug]!) : fallback;

const b64 = (v: unknown) => Buffer.from(JSON.stringify(v), "utf8").toString("base64");

const outDir = join(dirname(fileURLToPath(import.meta.url)), "..");

const quote = (v: string) => `'${v.replace(/'/g, "''")}'`;
/**
 * Single-line SQL string literal. Line breaks become chr(10) so every value stays on one line:
 * the Supabase SQL Editor mis-reads string literals that span several lines.
 */
const str = (v: string | null | undefined) =>
  v == null ? "null" : v.includes("\n") ? `(${v.split("\n").map(quote).join(" || chr(10) || ")})` : quote(v);
const json = (v: unknown) => `${str(JSON.stringify(v))}::jsonb`;

function header(file: string, about: string, rerun = "Safe to re-run: existing rows are left untouched.") {
  return `-- =====================================================================
-- ${file} — ${about}
-- GENERATED by \`npm run seed:sql\` from supabase/seed-data/seed-content.ts. Do not edit by hand.
-- ${rerun}
-- =====================================================================

`;
}

/** The Supabase SQL Editor breaks on line breaks or semicolons inside string literals. */
function assertEditorSafe(file: string, sql: string) {
  let inString = false;
  let start = 0;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (ch === "'") {
      if (inString && sql[i + 1] === "'") i++; // escaped quote
      else {
        inString = !inString;
        start = i;
      }
    } else if (inString && (ch === "\n" || ch === ";")) {
      throw new Error(`${file}: remove the ${ch === ";" ? "semicolon" : "line break"} from this text: ${sql.slice(start, start + 80)}`);
    }
  }
}

function write(file: string, about: string, body: string, rerun?: string) {
  assertEditorSafe(file, body);
  writeFileSync(join(outDir, file), header(file, about, rerun) + body.trim() + "\n");
  console.log("wrote", file);
}

